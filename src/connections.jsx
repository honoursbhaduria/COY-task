import React, { useCallback, useEffect, useRef, useState } from "react";
import { QrScanner } from "./qr-scanner.jsx";
import { api } from "./api.js";

export function Unsent({ profile, onClose }) {
  const dialog = useRef(null);
  const [body, setBody] = useState(""),
    [loading, setLoading] = useState(true),
    [busy, setBusy] = useState(false),
    [error, setError] = useState(""),
    [notice, setNotice] = useState(""),
    [attempt, setAttempt] = useState(0);
  useEffect(() => {
    dialog.current.showModal();
    const previous = document.body.style.overflow;
    document.body.style.overflow = "hidden";
    return () => {
      document.body.style.overflow = previous;
    };
  }, []);
  useEffect(() => {
    let active = true;
    setLoading(true);
    setError("");
    api(`/letters/${profile.id}`)
      .then((d) => {
        if (active) {
          setBody(d.letter.body);
          setLoading(false);
        }
      })
      .catch((e) => {
        if (active) setError(e.message);
      });
    return () => {
      active = false;
    };
  }, [profile.id, attempt]);
  async function save(e) {
    e.preventDefault();
    if (loading || busy) return;
    setBusy(true);
    setError("");
    try {
      await api(`/letters/${profile.id}`, { body });
      setNotice(
        body.trim()
          ? "Letter saved. It opens only when you both like each other."
          : "Letter removed.",
      );
    } catch (e) {
      setError(e.message);
    } finally {
      setBusy(false);
    }
  }
  return (
    <dialog
      ref={dialog}
      onCancel={onClose}
      className="letter-dialog"
      aria-labelledby="letter-title"
      aria-describedby="letter-description"
    >
      <header className="letter-header">
        <span className="sticker">✉ Unsent</span>
        <button
          autoFocus
          type="button"
          className="close-dialog"
          onClick={onClose}
          aria-label="Close letter"
        >
          ×
        </button>
      </header>
      <form id="unsent-form" className="letter-content" onSubmit={save}>
        <div className="letter-recipient">
          <img src={profile.photo} alt="" />
          <div>
            <span>A little courage, kept safe.</span>
            <h2 id="letter-title">For {profile.name}, someday.</h2>
          </div>
        </div>
        <p id="letter-description">
          Say what you feel. They’ll only read this if you both like each other.
        </p>
        <label className="letter-field" htmlFor="letter-body">
          Your letter
        </label>
        <textarea
          id="letter-body"
          rows="7"
          maxLength={2000}
          readOnly={loading || busy}
          value={body}
          onChange={(e) => {
            setBody(e.target.value);
            setNotice("");
          }}
          placeholder={
            loading
              ? "Opening your letter…"
              : "Something I’ve wanted to tell you…"
          }
          aria-describedby="letter-count letter-help"
        />
        <div className="letter-meta">
          <span id="letter-help">Just your words. No pressure.</span>
          <span id="letter-count">{body.length.toLocaleString()}/2,000</span>
        </div>
        {error && (
          <div role="alert" className="letter-feedback error">
            {error}
            {loading && (
              <button type="button" onClick={() => setAttempt((n) => n + 1)}>
                Try again
              </button>
            )}
          </div>
        )}
        {notice && (
          <p role="status" className="letter-feedback notice">
            {notice}
          </p>
        )}
        <p className="letter-footnote">
          Clear and save to remove. An opened letter may already have been read
          or copied.
        </p>
      </form>
      <footer className="letter-footer">
        <button
          type="submit"
          form="unsent-form"
          className="btn"
          disabled={loading || busy}
        >
          {busy ? "Saving…" : "Save letter"}
        </button>
        <p>Saving a letter doesn’t send a like.</p>
      </footer>
    </dialog>
  );
}

export function Encounters({ user, onMatch, onProfile }) {
  const [encounters, setEncounters] = useState([]),
    [scanning, setScanning] = useState(false),
    [busy, setBusy] = useState(false),
    [error, setError] = useState(""),
    [notice, setNotice] = useState("");
  const stopScanning = useCallback(() => setScanning(false), []);
  useEffect(() => {
    api("/encounters/saved")
      .then((d) => setEncounters(d.encounters))
      .catch((e) => setError(e.message));
  }, []);
  async function inspect(value) {
    setScanning(false);
    setBusy(true);
    setError("");
    try {
      let data;
      try {
        data = JSON.parse(value);
      } catch {
        throw Error("Scan a profile QR generated by Coy.");
      }
      if (!data || typeof data.id !== "string" || typeof data.name !== "string")
        throw Error("Invalid profile QR.");
      const result = await api("/encounters/profile", { profileId: data.id });
      setEncounters(result.encounters);
      setNotice("Added to your encounters. Decide later if you feel a spark.");
    } catch (e) {
      setError(e.message);
    } finally {
      setBusy(false);
    }
  }
  async function like(id) {
    setBusy(true);
    setError("");
    try {
      const result = await api(`/encounters/saved/${id}/like`, {});
      onMatch(result);
      setNotice(
        result.matched
          ? "The feeling is mutual!"
          : "Your interest is saved. They’ll only know if they like you too.",
      );
    } catch (e) {
      setError(e.message);
    } finally {
      setBusy(false);
    }
  }
  return (
    <section className="encounters">
      <span className="sticker">Encounter</span>
      <h1>
        A hello.
        <br />A second chance.
      </h1>
      <p className="lede">Scan their profile QR. Remember the moment.</p>
      <p className="encounter-intro">
        Your personal QR is in Profile. Show it to someone you meet, or scan
        theirs to save them here. Scanning never sends a like or shares a phone
        number.
      </p>
      <button className="quiet" onClick={onProfile}>
        Show my profile QR →
      </button>
      <div className="encounter-form">
        <h2>Scan their QR</h2>
        {scanning ? (
          <QrScanner onClose={stopScanning} onRead={inspect} />
        ) : (
          <button
            className="btn"
            disabled={busy}
            onClick={() => {
              setError("");
              setScanning(true);
            }}
          >
            Scan QR code
          </button>
        )}
        <p className="hint left">
          Camera frames are read on your device, never uploaded.
        </p>
      </div>
      <section className="saved-encounters">
        <h2>Your encounters</h2>
        {encounters.length ? (
          encounters.map((p) => (
            <article className="encounter-preview" key={p.id}>
              <img src={p.photo} alt="" />
              <h2>
                {p.name}, {p.age}
              </h2>
              <p>{p.bio}</p>
              <button
                className="btn"
                disabled={busy || !user.published}
                onClick={() => like(p.id)}
              >
                Add as a crush ♡
              </button>
              {!user.published && (
                <p className="hint">
                  Publish your profile before adding a crush.
                </p>
              )}
            </article>
          ))
        ) : (
          <p className="notice">
            No encounters yet. Scan someone’s QR to save them here.
          </p>
        )}
      </section>
      {error && (
        <p role="alert" className="error">
          {error}
        </p>
      )}
      {notice && (
        <p role="status" className="notice">
          {notice}
        </p>
      )}
    </section>
  );
}

