// Generate the async PostgreSQL implementation from the tested SQLite domain logic.
// This keeps validation, privacy and mutuality rules identical across both runtimes.
import fs from "node:fs";
import { parse } from "@babel/parser";
import traverseModule from "@babel/traverse";
import generatorModule from "@babel/generator";
import * as t from "@babel/types";
const traverse = traverseModule.default || traverseModule;
const generate = generatorModule.default || generatorModule;
const methods = new Set([
  "createSession",
  "resolveSession",
  "me",
  "edit",
  "location",
  "feed",
  "matches",
  "swipe",
  "photo",
  "readPhoto",
  "savedEncounters",
  "saveEncounter",
  "saveProfileEncounter",
  "crushEncounter",
  "createEncounter",
  "revokeEncounter",
  "previewEncounter",
  "likeEncounter",
  "ownLetter",
  "writeLetter",
  "connection",
  "sendMessage",
  "shareContact",
  "close",
]);
for (const name of ["store", "connections"]) {
  let source = fs.readFileSync(`server/${name}.js`, "utf8");
  if (name === "store") {
    source = source
      .replace(
        'import { DatabaseSync } from "node:sqlite";',
        'import { connectDatabase } from "./database.js";',
      )
      .replace('import { mkdirSync } from "node:fs";', "")
      .replace('import { dirname } from "node:path";', "")
      .replace('from "./errors.js"', 'from "../errors.js"')
      .replace('from "./seed.js"', 'from "../seed.js"');
    source = source
      .replace(
        /  if \(filename !== ":memory:"\)\s*mkdirSync\(dirname\(filename\), \{ recursive: true \}\);/,
        "",
      )
      .replace("new DatabaseSync(filename)", "connectDatabase(filename)");
    const start = source.indexOf("  const transaction = (fn) => {");
    const end = source.indexOf("  const api = {", start);
    source =
      source.slice(0, start) +
      "  const transaction = (fn) => db.transaction(fn);\n" +
      source.slice(end);
  }
  if (name === "connections")
    source = source.replace('from "./errors.js"', 'from "../errors.js"');
  const ast = parse(source, { sourceType: "module" });
  traverse(ast, {
    CallExpression: {
      exit(path) {
        const c = path.node.callee;
        let needs =
          t.isIdentifier(c) &&
          [
            "person",
            "transaction",
            "requireMatch",
            "validateLetterTarget",
            "encounter",
            "swipe",
            "createConnections",
          ].includes(c.name);
        if (t.isMemberExpression(c) && !c.computed) {
          if (["get", "all", "run"].includes(c.property.name)) needs = true;
          if (
            t.isIdentifier(c.object, { name: "db" }) &&
            ["exec", "transaction", "close"].includes(c.property.name)
          )
            needs = true;
          if (
            (t.isIdentifier(c.object, { name: "api" }) ||
              t.isThisExpression(c.object)) &&
            methods.has(c.property.name)
          )
            needs = true;
        }
        if (!needs || path.parentPath.isAwaitExpression()) return;
        const parent = path.getFunctionParent();
        if (parent) parent.node.async = true;
        path.replaceWith(t.awaitExpression(path.node));
        path.skip();
      },
    },
  });
  const header =
    "// Generated by scripts/generate-postgres.mjs. Edit server/" +
    name +
    ".js, then regenerate.\n";
  let output = generate(ast).code;
  if (name === "store")
    output = output
      .replace(
        "const db = connectDatabase(filename);",
        "const db = connectDatabase(filename); return await db.transaction(async () => {",
      )
      .replace(/return api;\s*}$/, "return api; }); }");
  fs.writeFileSync(`server/postgres/${name}.js`, header + output + "\n");
}
